def filas(nombre):
    f = [l.rstrip() for l in ICONOS[nombre].strip("\n").split("\n")]
    f = [l.ljust(16, ".")[:16] if len(l.rstrip()) <= 16 else l for l in f]
    assert len(f) == 16, (nombre, len(f))
    for l in f:
        assert len(l) == 16 and set(l) <= set("#+."), (nombre, l)
    return f

def rust(ruta):
    out = ["//! Iconos pixel art de 16x16 dibujados para Maker Studio (inspirados en el estilo de",
           "//! Font Awesome Pixel, sin copiar sus dibujos). Generado por scripts/iconos.py: '#' tinta,",
           "//! '+' relleno suave, '.' transparente.", "",
           "pub const SIZE: usize = 16;", ""]
    for n in ICONOS:
        out.append(f"pub const {n.upper()}: [&str; 16] = [")
        out += [f'    "{l}",' for l in filas(n)]
        out.append("];")
    open(ruta, "w").write("\n".join(out) + "\n")

def vista(ruta):
    from PIL import Image
    E, M = 8, 6
    nombres = list(ICONOS)
    im = Image.new("RGB", (len(nombres) * (16 * E + M) + M, 16 * E + 2 * M + 40), (248, 249, 254))
    for k, n in enumerate(nombres):
        x0 = M + k * (16 * E + M)
        for y, l in enumerate(filas(n)):
            for x, c in enumerate(l):
                col = {"#": (37, 37, 40), "+": (190, 196, 210)}.get(c)
                if col:
                    for dy in range(E):
                        for dx in range(E):
                            im.putpixel((x0 + x * E + dx, M + y * E + dy), col)
                # 1:1 debajo
                if l[x] in "#+":
                    im.putpixel((x0 + x, 16 * E + 2 * M + 8 + y), {"#": (37, 37, 40), "+": (190, 196, 210)}[l[x]])
    im.save(ruta)

if __name__ == "__main__":
    for n in ICONOS:
        filas(n)
    if sys.argv[1] == "rust":
        rust(sys.argv[2])
    else:
        vista(sys.argv[2])
